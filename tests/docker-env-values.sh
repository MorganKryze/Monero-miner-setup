#!/bin/bash
# The Docker installer checks every flag and secret against its rule before it writes a file:
# one error line names the flag and the rule, never a secret's value, and nothing is written.
# What it writes, Compose reads back byte for byte: every value double-quoted with \, " and $
# escaped. --threads writes a percentage and no forced count; a --memory under 2560 MiB warns
# that the miner will run in light mode. The installer runs from a fixture checkout with a stub
# docker; PATH holds only the stub and tool-link directories. Nothing is pulled, built or started.
# Run from the repository root. Prints FAIL lines, exits 1 on any miss.
rc=0
root=$PWD
fail() { echo "FAIL $*"; rc=1; }
w=$(mktemp -d) && [ -d "$w" ] || { echo "FAIL mktemp -d"; exit 1; }
trap 'rm -rf -- "$w"' EXIT
w=$(cd "$w" && pwd -P)
mkdir -p "$w/bin" "$w/tools" "$w/repo/docker"
: > "$w/repo/docker/compose.yml"
: > "$w/repo/docker/Dockerfile"
for t in cat cut date dirname head ls mktemp mv rm tr; do
  p=$(command -v "$t") || { echo "FAIL no $t on this host"; exit 1; }
  ln -s "$p" "$w/tools/$t"
done
cat > "$w/bin/docker" <<STUB
#!/bin/bash
PATH="$w/bin:$w/tools"
echo "\$*" >> "$w/docker.log"
case "\$*" in "compose version") exit 0 ;; --version) echo "Docker version stub" ;; *) exit 0 ;; esac
STUB
chmod +x "$w/bin/docker"
wallet=4AdUndXHHZ6cfufTMvppY6JwXNouMBzSkbLYfpAV5Usx3skxNgYeYTRj5UzqtReoS44qo9mtmXCqY45DJ852K5Jv2684Rge
env="$w/repo/docker/.env" vpn="$w/repo/docker/.env.vpn"
utf8=$(locale -a 2>/dev/null | grep -iE '^(c|en_us)\.utf-?8$' | head -1)

# run <name> <args...>: a first run in the fixture checkout (no file from an earlier run).
# VPN secrets come from the environment variables of the same name. Sets out, err, code.
run() {
  local name=$1; shift
  rm -f "$w/docker.log" "$env" "$vpn"
  (cd "$w/repo" && env -i HOME="$w" PATH="$w/bin:$w/tools" ${utf8:+LC_ALL=$utf8} \
    ${WG_KEY+"WIREGUARD_PRIVATE_KEY=$WG_KEY"} ${WG_ADDR+"WIREGUARD_ADDRESSES=$WG_ADDR"} \
    ${VPN_USER+"OPENVPN_USER=$VPN_USER"} ${VPN_PASS+"OPENVPN_PASSWORD=$VPN_PASS"} \
    "$BASH" "$root/scripts/docker_setup.sh" -w "$wallet" -y "$@") > "$w/out" 2> "$w/err"
  code=$?
  out=$(sed 's/\x1b\[[0-9;]*m//g' "$w/out") err=$(sed 's/\x1b\[[0-9;]*m//g' "$w/err")
}
want() { # name, label, expected, got
  [ "$3" = "$4" ] || { echo "FAIL $1: $2"; diff <(printf '%s\n' "$3") <(printf '%s\n' "$4") | sed 's/^/    /'; rc=1; }
}
body() { grep -v '^# Generated by scripts/docker_setup.sh on ' "$1"; }
refused() { # name, error line, args...
  local name=$1 line=$2; shift 2
  run "$name" "$@"
  want "$name" exit 1 "$code"
  want "$name" stderr "[  ERROR  ] $line" "$err"
  [ ! -e "$env" ] && [ ! -e "$vpn" ] || fail "$name: a file was written"
  [ ! -e "$w/docker.log" ] || [ "$(cat "$w/docker.log")" = "compose version"$'\n'"--version" ] || fail "$name: docker calls"
}

# The defaults, whole file but its date line.
run defaults
want defaults exit 0 "$code"
want defaults .env "$(printf '%s\n' "WALLET_ADDRESS=\"$wallet\"" 'WORKER_NAME="docker_miner"' 'POOL_URL="gulf.moneroocean.stream"' \
  'DONATE_LEVEL="0"' 'MAX_THREADS_PERCENT="75"' 'FORCE_THREAD_COUNT=""' 'CPU_COUNT="2.0"' 'MEMORY_LIMIT="3g"' \
  'PAUSE_ON_BATTERY="false"' 'PAUSE_ON_ACTIVE="false"' 'XMRIG_IMAGE="ghcr.io/morgankryze/monero-miner-setup:latest"')" "$(body "$env")"
want defaults stderr "" "$err"

# Values at the edges of their rules, written as passed.
run edges -w "$wallet.Rig42" --worker-name 'rig@home:1+a.b-c_d' --pool stratum+ssl://pool.example.com:443 --donate 5 \
  --threads 100 --force-threads 1024 --cpus 1.5 --memory 2560m --pause-battery --pause-active \
  --image ghcr.io/x/y:v1@sha256:0123
want edges exit 0 "$code"
want edges .env "$(printf '%s\n' "WALLET_ADDRESS=\"$wallet.Rig42\"" 'WORKER_NAME="rig@home:1+a.b-c_d"' \
  'POOL_URL="stratum+ssl://pool.example.com:443"' 'DONATE_LEVEL="5"' 'MAX_THREADS_PERCENT="100"' 'FORCE_THREAD_COUNT="1024"' \
  'CPU_COUNT="1.5"' 'MEMORY_LIMIT="2560m"' 'PAUSE_ON_BATTERY="true"' 'PAUSE_ON_ACTIVE="true"' 'XMRIG_IMAGE="ghcr.io/x/y:v1@sha256:0123"')" "$(body "$env")"
want edges stderr "" "$err"
# --threads alone: a percentage, no forced count.
run threads --threads 50
grep -qx 'MAX_THREADS_PERCENT="50"' "$env" && grep -qx 'FORCE_THREAD_COUNT=""' "$env" || fail "threads: $(grep THREAD "$env" | tr '\n' ' ')"

# Memory under the 2560 MiB the fast mode needs: one warning, the value written all the same.
for m in 1g 2559m 2684354559b 2621439k; do
  run "memory $m" --memory "$m"
  want "memory $m" exit 0 "$code"
  want "memory $m" stderr "[ WARNING ] --memory $m is under the 2560 MiB RandomX's fast mode needs: the miner will run in light mode, at a fraction of the hashrate." "$err"
  grep -qx "MEMORY_LIMIT=\"$m\"" "$env" || fail "memory $m: not written"
done
for m in 3g 2560m 2621440k 2684354560b 2684354560; do
  run "memory $m" --memory "$m"
  want "memory $m" stderr "" "$err"
done

# Each flag's rule, broken.
for bad in 'a b' 'x","url":"evil' 'a#b' 'a$b' 'rigé' "$(printf 'a%.0s' {1..65})"; do
  refused "worker $bad" "--worker-name must be 1 to 64 letters, digits or . _ - @ : + characters." --worker-name "$bad"
done
for bad in 'a;b' 'pool:0' 'pool:65536' 'http://pool' '-pool' 'x";touch${IFS}/tmp/pwned;#e;s#x#'; do
  refused "pool $bad" "--pool must be a host name or IPv4 address, optionally after stratum+tcp:// or stratum+ssl:// and before a :port from 1 to 65535." --pool "$bad"
done
for bad in 6 -1 x 1.0; do refused "donate $bad" "--donate must be a whole number from 0 to 5." --donate "$bad"; done
for bad in 0 101 x 75%; do refused "threads $bad" "--threads must be a whole number from 1 to 100." --threads "$bad"; done
for bad in 0 1025 x ' 2'; do refused "force '$bad'" "--force-threads must be a whole number from 1 to 1024." --force-threads "$bad"; done
for bad in 0 0.0 -1 1.2345 abc '' 2,0; do refused "cpus '$bad'" "--cpus must be a positive decimal number, such as 2 or 1.5." --cpus "$bad"; done
for bad in 3G 1.5g x '' 3gb '1g;x' 0 0g 000m; do refused "memory '$bad'" "--memory must be digits with an optional b, k, m or g, such as 3g." --memory "$bad"; done
for bad in 'a b' 'a;b' 'img$x' ''; do refused "image '$bad'" "--image must hold only letters, digits and . _ - / : @ characters." --image "$bad"; done
refused location-newline "--vpn-location must be one line with no control character." --vpn mullvad --vpn-location $'Zurich\nFIREWALL=off'
refused location-tab "--vpn-location must be one line with no control character." --vpn mullvad --vpn-location $'Zur\tich'
refused wallet-suffix "Invalid wallet: 95 or 106 base58 characters starting with 4 or 8, then optionally one '.' and 1 to 64 letters or digits." -w "$wallet."

# Secrets: a control character refuses the run without printing the secret; from a file, its final
# newline goes and any other line refuses it.
WG_KEY=$'k\nFIREWALL_ENABLED_DISABLING_IT_SHOOTS_YOU_IN_YOUR_FOOT=on' WG_ADDR=10.64.0.1/32 \
  refused wg-key-newline "The WireGuard private key must be one line with no control character." --vpn mullvad
printf '%s' "$out$err" | grep -q 'SHOOTS' && fail "wg-key-newline: the secret was printed"
WG_KEY=k WG_ADDR=$'10.64.0.1/32\r' refused wg-addr-cr "The WireGuard address must be one line with no control character." --vpn protonvpn
VPN_USER=$'u\x01' VPN_PASS=p refused vpn-user "The OpenVPN username must be one line with no control character." --vpn pia
VPN_USER=u VPN_PASS=$'p\x7f' refused vpn-pass "The OpenVPN password must be one line with no control character." --vpn nordvpn
printf 'line1\nline2\n' > "$w/key"
WG_ADDR=10.64.0.1/32 refused key-file-two-lines "The WireGuard private key must be one line with no control character." --vpn mullvad --wg-key-file "$w/key"
printf 'onlyline\n' > "$w/key"
WG_ADDR=10.64.0.1/32 run key-file --vpn mullvad --wg-key-file "$w/key"
want key-file exit 0 "$code"
grep -qx 'WIREGUARD_PRIVATE_KEY="onlyline"' "$vpn" || fail "key-file: $(grep KEY "$vpn")"

# Secrets holding $, #, quotes, backslashes and non-ASCII letters: the escaped form, and that form
# read back as Compose does (inside double quotes, a backslash keeps the next character) is the
# value, byte for byte. Every provider's whole file, but its date line; none sets FIREWALL.
secret='pa$$w0rd #tail "q" back\slash ab$HOMEcd ü'
escaped='pa\$\$w0rd #tail \"q\" back\\slash ab\$HOMEcd ü'
unescape() { local v=$1 out="" c; while [ -n "$v" ]; do c=${v:0:1} v=${v:1}; if [ "$c" = '\' ]; then c=${v:0:1} v=${v:1}; fi; out+=$c; done; printf '%s' "$out"; }
want round-trip value "$secret" "$(unescape "$escaped")"
WG_KEY=$secret WG_ADDR=10.64.0.1/32 run mullvad --vpn mullvad --vpn-location 'Zürich'
want mullvad .env.vpn "$(printf '%s\n' 'VPN_SERVICE_PROVIDER="mullvad"' 'VPN_TYPE="wireguard"' "WIREGUARD_PRIVATE_KEY=\"$escaped\"" \
  'WIREGUARD_ADDRESSES="10.64.0.1/32"' 'SERVER_CITIES="Zürich"' 'TZ="UTC"' 'LOG_LEVEL="info"')" "$(body "$vpn")"
want mullvad mode "-rw-------" "$(ls -l "$vpn" | cut -c1-10)"
WG_KEY=k WG_ADDR=10.2.0.2/32 run protonvpn --vpn protonvpn
want protonvpn .env.vpn "$(printf '%s\n' 'VPN_SERVICE_PROVIDER="protonvpn"' 'VPN_TYPE="wireguard"' 'WIREGUARD_PRIVATE_KEY="k"' \
  'WIREGUARD_ADDRESSES="10.2.0.2/32"' 'TZ="UTC"' 'LOG_LEVEL="info"')" "$(body "$vpn")"
VPN_USER=user VPN_PASS=$secret run pia --vpn pia --vpn-location Swiss
want pia .env.vpn "$(printf '%s\n' 'VPN_SERVICE_PROVIDER="private internet access"' 'VPN_TYPE="openvpn"' 'OPENVPN_USER="user"' \
  "OPENVPN_PASSWORD=\"$escaped\"" 'SERVER_REGIONS="Swiss"' 'TZ="UTC"' 'LOG_LEVEL="info"')" "$(body "$vpn")"
VPN_USER=user VPN_PASS=p run nordvpn --vpn nordvpn --vpn-location Switzerland
want nordvpn .env.vpn "$(printf '%s\n' 'VPN_SERVICE_PROVIDER="nordvpn"' 'VPN_TYPE="openvpn"' 'OPENVPN_USER="user"' \
  'OPENVPN_PASSWORD="p"' 'SERVER_COUNTRIES="Switzerland"' 'TZ="UTC"' 'LOG_LEVEL="info"')" "$(body "$vpn")"
want nordvpn stderr "[ WARNING ] NordVPN's terms may prohibit crypto-mining on your plan. Verify before running long." "$err"
[ "$rc" -eq 0 ] && echo "PASS docker-env-values"
exit "$rc"
